#!/bin/bash
# archive-index.sh — build files/ARCHIVE-INDEX.md by working backwards from use.
#
# Every document in the evidence archive is classified by what it is DOING for the
# project, not by who filed it. The tree already records who filed it; that is the one
# question nobody arrives with.
#
#   CITED         a published page cites it. This is the evidence of record.
#   WORKING       named in memory/ but not yet on the site. In play, not yet public.
#   BASELINE      a comparison jurisdiction. Never cited, and doing real work:
#                 "abnormal" is a comparative claim and these are what it rests on.
#   CORE-UNCITED  Gallatin / Sumner / IDB subject matter that nothing has used yet.
#   SPECULATIVE   acquired in case it mattered. Largely unassessed.
#
# Re-run after adding documents or publishing new citations.  No arguments.

set -euo pipefail
cd "$(dirname "$0")/../.."
ROOT="$PWD"
OUT="files/ARCHIVE-INDEX.md"
ARCH="state_of_tennessee sumner_county usa_federal web_articles the_players podcasts"

tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT

find $ARCH -type f \( -name '*.pdf' -o -name '*.txt' -o -name '*.csv' -o -name '*.md' \) \
  -not -name 'README.md' -not -name 'pdf-index.csv' -not -name 'FINDING-AID.md' \
  -not -path '*/derived/*' | sort > "$tmp/sources"

# A published citation survives as /sources/<stem>/ after the publish rewrite.
grep -rhoE '/sources/[A-Za-z0-9_./-]+' web/content/ 2>/dev/null \
  | sed 's|/sources/||; s|/$||; s|.*/||' | sort -u > "$tmp/site"
grep -rhoE '[A-Za-z0-9_.-]+\.(pdf|txt|csv)' memory/ 2>/dev/null \
  | sed 's|.*/||' | sort -u > "$tmp/mem"

: > "$tmp/classified"
while read -r p; do
  b=$(basename "$p"); stem="${b%.*}"
  if   grep -qxF "$b" "$tmp/site" || grep -qxF "$stem" "$tmp/site"; then c=CITED
  elif grep -qxF "$b" "$tmp/mem"; then c=WORKING
  else case "$p" in
      *gibson*|*hamilton*|*westmoreland*|*portland*)  c=BASELINE;;
      podcasts/*|web_articles/*|the_players/*)        c=SPECULATIVE;;
      *)                                              c=CORE-UNCITED;;
    esac
  fi
  printf '%s\t%s\n' "$c" "$p" >> "$tmp/classified"
done < "$tmp/sources"

count() { grep -c "^$1	" "$tmp/classified" || true; }
list()  { grep "^$1	" "$tmp/classified" | cut -f2; }

TOTAL=$(wc -l < "$tmp/classified")

{
cat <<HEADER
# Archive Index

Every document in the evidence archive, classified by **what it is doing for the
project** rather than by who filed it. The directory tree already records who filed it,
and that is the one question nobody arrives with.

Generated by \`files/bin/archive-index.sh\`. Re-run it after adding documents or
publishing new citations; do not hand-edit this file.

Companion to \`files/DATA_MAP.md\`, which tells you where things live. This tells you
what they are for.

Built $(date +%Y-%m-%d) · $TOTAL documents

| Class | Count | Meaning |
|---|---:|---|
| CITED | $(count CITED) | A published page cites it. The evidence of record. |
| WORKING | $(count WORKING) | Named in \`memory/\`, not yet on the site. |
| BASELINE | $(count BASELINE) | Comparison jurisdiction. Never cited, still doing work. |
| CORE-UNCITED | $(count CORE-UNCITED) | Core subject matter nothing has used yet. |
| SPECULATIVE | $(count SPECULATIVE) | Acquired in case. Largely unassessed. |

**Derived extractions are excluded.** Everything under a \`derived/\` directory is
machine output, regenerable, and never cited by rule. Its index is the \`pdf-index.csv\`
sitting beside it.

---

## CITED — the evidence of record

These carry published claims. If one of these moves, is renamed, or turns out to say
something other than what the page says it says, a live page is wrong. Treat as frozen.

HEADER

list CITED | sed 's|^|- `|; s|$|`|'

cat <<'MID'

---

## WORKING — in play, not yet public

Named in `memory/` but not cited by any page. These are the documents the investigation
is currently reasoning from. The shortest path from here to a published claim.

MID

list WORKING | sed 's|^|- `|; s|$|`|'

cat <<'MID2'

---

## BASELINE — what normal looks like

Comparison jurisdictions. None of these is cited and that undersells them: *abnormal is a
comparative claim*, and the ability to say the Gallatin IDB is unusual rests on having
gone and looked at ones that are not.

**If a published page calls something unusual, atypical, or an outlier, the comparison
belongs in a citation.** Uncited baseline work is the most attackable kind, because from
outside it is indistinguishable from an assumption.

MID2

list BASELINE | sed 's|^|- `|; s|$|`|'

cat <<'MID3'

---

## CORE-UNCITED — on the subject, unused

Gallatin, Sumner County, and IDB material that no page cites and no memory file names.
Not dead weight; unspent. This is where a contradiction would be hiding, because a
document nobody has opened is a document nobody has been troubled by.

MID3

for d in $(list CORE-UNCITED | sed 's|/[^/]*$||' | sort -u); do
  n=$(list CORE-UNCITED | grep -c "^$d/")
  echo ""
  echo "**\`$d/\`** — $n"
  list CORE-UNCITED | grep "^$d/" | sed "s|^$d/||; s|^|  - |"
done

cat <<'MID4'

---

## SPECULATIVE — acquired in case

Podcasts, web articles, and player profiles gathered without a specific claim in view.
Triage rather than read: most will be nothing, and the cost of finding out is one skim
each.

MID4

for d in $(list SPECULATIVE | sed 's|/[^/]*$||' | sort -u); do
  n=$(list SPECULATIVE | grep -c "^$d/")
  echo ""
  echo "**\`$d/\`** — $n"
  list SPECULATIVE | grep "^$d/" | sed "s|^$d/||; s|^|  - |"
done

cat <<'FOOT'

---

## How this is computed

- **CITED** — the basename or stem appears in a `/sources/...` link under `web/content/`.
  The publish step rewrites `@/` citations into that form in place, so this reads the
  published state rather than the authoring shorthand.
- **WORKING** — the filename appears anywhere in `memory/`.
- **BASELINE** — path names a comparison jurisdiction (Gibson, Hamilton, Westmoreland,
  Portland).
- **SPECULATIVE** — lives under `podcasts/`, `web_articles/`, or `the_players/`.
- **CORE-UNCITED** — everything else.

A file that is renamed without its citation being updated will silently fall from CITED to
CORE-UNCITED. That drop is a bug, not a reclassification. Publishing already fails on a
missing cited document, so the visible symptom is here rather than in a broken build.
FOOT
} > "$OUT"

echo "wrote $OUT — $TOTAL documents"
printf '  %-13s %s\n' CITED "$(count CITED)" WORKING "$(count WORKING)" \
  BASELINE "$(count BASELINE)" CORE-UNCITED "$(count CORE-UNCITED)" SPECULATIVE "$(count SPECULATIVE)"
