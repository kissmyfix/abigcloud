def _find_root(start):
    """The project root is where .git lives. Inferring it from the opened file's
    depth broke the moment a file moved; this does not."""
    d = os.path.dirname(start)
    while d != "/":
        if os.path.isdir(os.path.join(d, ".git")):
            return d
        d = os.path.dirname(d)
    return os.path.dirname(os.path.dirname(start))

ROOT = _find_root(MD)

SKIP = {".git", "node_modules", "dist", ".astro", "venv", "__pycache__",
        ".remember", "derived"}

def listing():
    """The pages of the website, and nothing else.

    This editor exists to write the site. The research tree is 250-odd markdown
    and text files and none of them publish, so offering them turned the picker
    into a haystack. The list is `web/index.md` plus everything under
    `web/content/`, grouped the way the directory reads on GitHub.

    `web/content/sources/` is left out: those pages are generated by the publish
    step and overwritten on the next run, so editing one only loses work.
    """
    out = []
    for base in (os.path.join(ROOT, "web", "content"),):
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = [d for d in dirnames if d not in SKIP and not d.startswith(".")]
            for fn in filenames:
                if not fn.endswith(".md") or fn.startswith("."):
                    continue
                rel = os.path.relpath(os.path.join(dirpath, fn), ROOT).replace(os.sep, "/")
                if rel.startswith("web/content/sources/"):
                    continue
                out.append({"rel": rel, "size": os.path.getsize(os.path.join(ROOT, rel))})

    home = os.path.join(ROOT, "web", "index.md")
    if os.path.isfile(home):
        out.append({"rel": "web/index.md", "size": os.path.getsize(home)})

    for e in out:
        rel = e["rel"]
        if rel == "web/index.md":
            e["group"], e["label"] = "Home", "index.md"
        else:
            inner = rel[len("web/content/"):]
            e["group"] = "Top level" if "/" not in inner else inner.split("/")[0]
            e["label"] = inner
    order = {"Home": 0, "Top level": 1}
    out.sort(key=lambda r: (order.get(r["group"], 2), r["group"], r["rel"]))
    return out

def resolve(rel):
    """Map a client-supplied path to a real file inside ROOT, or None."""
    if not rel:
        return MD
    full = os.path.normpath(os.path.join(ROOT, rel))
    return full if full.startswith(ROOT) and os.path.isfile(full) else None

